/// G8: the HTTP response of every client-visible error scenario (status, headers, body).
///
/// Requests go through the real application (`bitview_server::app`: routes, rejections, the
/// JSON error rewrite, POST no-store, CORS) over the offline import, with no mempool and an
/// unreachable node; the volatile `x-response-time` header is dropped. Failures that no offline
/// request can reach are rendered from the server's error type; the remaining foundation
/// variants share the same fallback arm as `lower: io`. Names describe behaviour, so a refactor
/// of how errors are built keeps the names and the diff shows exactly which responses changed.
pub(crate) fn render_errors(plugins: &AllPlugins) -> Result<Snapshot> {
    let runtime = Builder::new_multi_thread().enable_all().build()?;
    let data = tempdir()?;
    let mut out =
        String::from("# Generated by `cargo api` (crates/bitview_devtools). Do not edit.\n");
    runtime.block_on(async {
        let query = AsyncQuery::build(&plugins.defaults, None);
        let app = app(
            &query,
            ServerConfig {
                bind: IpAddr::V4(Ipv4Addr::LOCALHOST),
                port: Port::DEFAULT,
                data_path: data.path().to_path_buf(),
                website: Website::Disabled,
                cdn_cache_mode: CdnCacheMode::default(),
                max_weight: DEFAULT_MAX_WEIGHT,
                max_utxos: DEFAULT_MAX_UTXOS,
            },
        )
        .await?;
        for (name, method, uri, body) in requests() {
            let request = Request::builder()
                .method(method)
                .uri(uri)
                .body(Body::from(body))
                .map_err(|_| Error::Internal("invalid scenario request"))?;
            let Ok(response) = app.clone().oneshot(request).await;
            render(&mut out, name, response).await?;
        }
        for (name, error) in errors() {
            render(&mut out, name, error.into_response()).await?;
        }
        Ok::<_, Error>(())
    })?;
    runtime.shutdown_background();
    Ok(Snapshot {
        file: "errors.txt",
        contents: out,
    })
}

async fn render(out: &mut String, name: &str, response: Response<Body>) -> Result<()> {
    let (parts, body) = response.into_parts();
    let body = to_bytes(body, usize::MAX)
        .await
        .map_err(|_| Error::Internal("unreadable error body"))?;
    let mut headers = parts
        .headers
        .iter()
        .filter(|(key, _)| key.as_str() != "x-response-time")
        .map(|(key, value)| format!("{key}: {}", value.to_str().unwrap_or("<binary>")))
        .collect::<Vec<_>>();
    headers.sort();
    out.push_str(&format!("\n## {name}\n{}\n", parts.status));
    for header in headers {
        out.push_str(&header);
        out.push('\n');
    }
    out.push_str(&String::from_utf8_lossy(&body));
    out.push('\n');
    Ok(())
}

