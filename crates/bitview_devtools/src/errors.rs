/// Conditions no offline request reaches, rendered from the server's error type. The server's
/// own messages are copied from their call sites, so these pin the mapping, not the wording.
fn errors() -> Vec<(&'static str, ServerError)> {
    let json = serde_json::from_str::<u8>("x").unwrap_err();
    let brk = |name: &'static str, error: Error| (name, ServerError::from(error));
    vec![
        // Failures below the API layer.
        brk("lower: io", Error::IO(io::Error::other("disk"))),
        brk("lower: internal", Error::Internal("invariant broken")),
        brk(
            "lower: not found",
            Error::NotFound("blk file missing".into()),
        ),
        brk("lower: parse", Error::Parse("bad hex in block file".into())),
        brk(
            "lower: out of range",
            Error::OutOfRange("position past end".into()),
        ),
        brk(
            "lower: unsupported type",
            Error::UnsupportedType("op_return".into()),
        ),
        brk("lower: json", Error::SerdeJSON(json)),
        brk(
            "lower: no rpc credentials",
            Error::NoRpcCredentials {
                cookie: PathBuf::from("/btc/.cookie"),
            },
        ),
        // Node and API conditions.
        brk(
            "broadcast rejected by node",
            Error::Parse("bad-txns-inputs-missingorspent".into()),
        ),
        brk(
            "weight exceeded",
            Error::WeightExceeded {
                requested: 10,
                max: 5,
            },
        ),
        brk("too many utxos", Error::TooManyUtxos),
        brk("query read timeout", Error::ReadTimeout),
        // Built by the server itself.
        ("request deadline (POST)", ServerError::timeout(true)),
        ("request deadline (GET)", ServerError::timeout(false)),
        (
            "broadcast queue full",
            ServerError::overloaded("too many pending transaction submissions"),
        ),
        ("handler panic", ServerError::internal("Unknown panic")),
    ]
}
