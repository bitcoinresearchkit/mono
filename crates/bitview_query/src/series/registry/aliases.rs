// Keep the binary-search precondition and direct targets true before this can compile.
const _: () = {
    let mut i = 0;
    while i < RENAMES.len() {
        if i > 0 {
            assert!(precedes(RENAMES[i - 1].0, RENAMES[i].0));
        }
        let mut j = 0;
        while j < RENAMES.len() {
            assert!(precedes(RENAMES[i].1, RENAMES[j].0) || precedes(RENAMES[j].0, RENAMES[i].1));
            j += 1;
        }
        i += 1;
    }
};

const fn precedes(left: &str, right: &str) -> bool {
    let left = left.as_bytes();
    let right = right.as_bytes();
    let mut i = 0;
    while i < left.len() && i < right.len() {
        if left[i] != right[i] {
            return left[i] < right[i];
        }
        i += 1;
    }
    left.len() < right.len()
}

pub(crate) fn canonical_name(name: &str) -> &str {
    RENAMES
        .binary_search_by_key(&name, |&(old, _)| old)
        .map_or(name, |at| RENAMES[at].1)
}

pub(super) fn rename_catalog(tree: &mut TreeNode) {
    match tree {
        TreeNode::Branch(branch) => {
            for child in branch.children.values_mut() {
                rename_catalog(child);
            }
        }
        TreeNode::Leaf(leaf) => {
            let name = canonical_name(&leaf.leaf.name);
            if name != leaf.leaf.name {
                leaf.leaf.name = name.to_owned();
            }
        }
    }
}

pub(super) fn add_legacy_names<'a>(by_series: &mut FxHashMap<&'a str, Series<'a>>) {
    for &(old, new) in RENAMES {
        if let Some(series) = by_series.get(new).cloned() {
            let previous = by_series.insert(old, series);
            debug_assert!(previous.is_none(), "alias collides: {old}");
        }
    }
}
